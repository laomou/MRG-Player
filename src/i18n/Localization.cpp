Language languageFromSetting(int value) {
  return value == static_cast<int>(Language::SimplifiedChinese)
             ? Language::SimplifiedChinese
             : Language::English;
}

const char *tr(TextId id, Language language) {
  const auto &entry = kText[static_cast<std::size_t>(id)];
  return language == Language::SimplifiedChinese ? entry.chinese
                                                 : entry.english;
}

